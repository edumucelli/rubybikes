class RubyBikes
  module Native
    class JsonProviders
      DECOBIKE_HEADERS = {
        'Accept' => 'application/xml, text/xml, */*; q=0.01',
        'Accept-Language' => 'en-US,en;q=0.9',
        'User-Agent' => 'Mozilla/5.0 (Linux; Android 13; Pixel 6) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/112.0.0.0 Mobile Safari/537.36',
        'X-Requested-With' => 'com.citibike.miami'
      }.freeze
      BICINCITTA_STATUSES = { 0 => 'online', 1 => 'maintenance', 2 => 'offline', 3 => 'under construction', 4 => 'planned' }.freeze
      DETAIL_JSON_HEADERS = { 'Content-Type' => 'application/json; charset=utf-8' }.freeze
      FSM_ENDPOINT = 'https://www.tel-o-fun.co.il/api/privatearea/v1'
      FSM_HEADERS = { 'Accept-Language' => 'en' }.freeze
      XIAN_SOAP = <<~XML
        <soapenv:Envelope xmlns:soapenv="http://schemas.xmlsoap.org/soap/envelope/" xmlns:q0="http://ws.itcast.cn/" xmlns:xsd="http://www.w3.org/2001/XMLSchema" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">
          <soapenv:Body><q0:findBikeSites></q0:findBikeSites></soapenv:Body>
        </soapenv:Envelope>
      XML

      # Metadata generated by these clients belongs to their description too,
      # before the first network update.
      def initialize(spec, parameters, key: nil)
        super
        case spec.fetch('module')
        when 'bicincitta'
          endpoint = p('endpoint') || 'https://www.bicincitta.com/'
          @meta['source'] = URI.join(endpoint, "frmLeStazioni.aspx?ID=#{p('city_ids').fetch(0)}").to_s
        when 'pedalada'
          @meta['company'] = Array(@parameters.fetch('meta')['company']) + Array(spec.fetch('meta')['company'])
        end
      end

      def update_bixi
        detail_xml(p('feed_url')).xpath('/stations/station').each do |node|
          name = xml_text(node, 'name')
          terminal = xml_text(node, 'terminalName')
          extra = {
            'uid' => number(xml_text(node, 'id')),
            'name' => name,
            'terminalName' => terminal,
            'locked' => xml_boolean?(xml_text(node, 'locked')),
            'installed' => xml_boolean?(xml_text(node, 'installed')),
            'temporary' => xml_boolean?(xml_text(node, 'temporary')),
            'installDate' => xml_text(node, 'installDate'),
            'removalDate' => xml_text(node, 'removalDate')
          }
          updated = xml_text(node, 'latestUpdateTime')
          extra['latestUpdateTime'] = updated if updated && updated != '0'
          station("#{terminal} - #{name}", xml_text(node, 'lat'), xml_text(node, 'long'),
                  number(xml_text(node, 'nbBikes')), number(xml_text(node, 'nbEmptyDocks')), extra)
        end
      end

      def update_decobike
        detail_xml(p('feed_url'), headers: DECOBIKE_HEADERS).xpath('//location').each do |node|
          uid = xml_text(node, 'Id')
          address = xml_text(node, 'Address')
          station("#{uid} - #{address}", xml_text(node, 'Latitude'), xml_text(node, 'Longitude'),
                  number(xml_text(node, 'Bikes')), number(xml_text(node, 'Dockings')),
                  { 'uid' => uid, 'address' => address })
        end
      end

      def update_xian
        document = detail_xml(p('endpoint'), method: 'POST', data: XIAN_SOAP,
                                             headers: { 'Content-Type' => 'text/xml; charset=utf-8' })
        payload = document.xpath('string(//ns1:out)', 'ns1' => 'http://inter.webservice.web.ptpportal.guloo.org').delete(' ')
        JSON.parse(payload).each do |item|
          slots = number(item.fetch('locknum'))
          free = number(item.fetch('emptynum'))
          station(item.fetch('sitename'), item.fetch('latitude'), item.fetch('longitude'), slots - free, free,
                  { 'uid' => item.fetch('siteid'), 'slots' => slots, 'address' => item.fetch('location') })
        end
      end

      def update_bicincitta
        endpoint = p('endpoint') || 'https://www.bicincitta.com/'
        p('city_ids').each do |city|
          payload = json(URI.join(endpoint, 'frmLeStazioniComune.aspx/RefreshStations').to_s,
                         method: 'POST', data: JSON.generate('IDComune' => city.to_s), headers: DETAIL_JSON_HEADERS)
          payload.fetch('d').drop(1).each do |raw|
            uid, lat, lon, name, number, status = raw.split('§')
            extra = { 'uid' => uid, 'number' => number(number), 'status' => BICINCITTA_STATUSES.fetch(number(status)) }
            detail = json(URI.join(endpoint, 'frmLeStazioni.aspx/RefreshPopup').to_s,
                          method: 'POST', data: JSON.generate('IDStazione' => uid.to_s), headers: DETAIL_JSON_HEADERS)
            _, reviews, score, _, availability = detail.fetch('d').split('§').take(5)
            extra['score'] = Float(score.tr(',', '.'))
            extra['reviews'] = number(reviews)
            station(name, bicincitta_coordinate(lat), bicincitta_coordinate(lon), availability.count('4'), availability.count('0'), extra)
          end
        end
      end

      def update_pedalada
        endpoint = p('endpoint')
        json("#{endpoint}/php/get-stations-details-map.php").each do |item|
          uid = item.fetch('stationNumber')
          slots = item.fetch('maximumNumberOfRides')
          detail = json("#{endpoint}/php/get-station-details-and-rides.php", params: { 'n' => uid })
          bikes = detail.fetch('rides').length
          extra = {
            'uid' => uid, 'slots' => slots, 'online' => item.fetch('state') == 1,
            'photo' => "#{endpoint}/images/stations/station_#{uid}.jpg",
            'status' => pedalada_status(detail.fetch('details').fetch(0))
          }
          station(item.fetch('stationName'), item.fetch('latitude'), item.fetch('longitude'), bikes, slots - bikes, extra)
        end
      end

      def update_fsm
        json("#{FSM_ENDPOINT}/map", headers: FSM_HEADERS).fetch('stations').each do |item|
          detail = json("#{FSM_ENDPOINT}/station/#{item.fetch('id')}", headers: FSM_HEADERS)
          electric = item.fetch('omniBikes')
          normal = item.fetch('novatechBikes')
          electric_slots = detail.fetch('availableOmniPoles')
          normal_slots = detail.fetch('availableNovatechPoles')
          extra = {
            'uid' => item.fetch('id'), 'number' => item.fetch('stationNumber'),
            'shabbat' => item.fetch('isShabbatStation'), 'has_ebikes' => true,
            'ebikes' => electric, 'normal_bikes' => normal, 'normal_slots' => normal_slots,
            'e_slots' => electric_slots, 'address' => detail.fetch('address')
          }
          station(item.fetch('name'), item.fetch('location').fetch('lat'), item.fetch('location').fetch('lng'),
                  normal + electric, normal_slots + electric_slots, extra)
        end
      end

      private

      def detail_xml(url, **options)
        Nokogiri::XML(request(url, **options)) { |config| config.strict.nonet }
      end

      def xml_text(node, name)
        node.at_xpath(name)&.text
      end

      def xml_boolean?(value)
        %w[yes true t 1].include?(value.downcase)
      end

      def bicincitta_coordinate(value)
        Float(value[/\d+\.\d{5,15}/] || value)
      end

      def pedalada_status(detail)
        return 'maintenance' if truthy?(detail.fetch('stationInMaintenance'))

        truthy?(detail.fetch('stationIsOpen')) ? 'open' : 'closed'
      end
    end
  end
end
